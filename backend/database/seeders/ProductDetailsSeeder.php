        foreach ($this->details() as $sku => $payload) {
            $bySku[strtolower($sku)] = $payload;
        }

        Product::query()->get()->each(function (Product $product) use ($bySku) {
            $payload = $bySku[strtolower((string) $product->sku)] ?? null;
            if ($payload === null) {
                return;
            }

            $product->fill($payload)->save();
        });

        $current = (int) Setting::getValue(Constants::SETTING_MARKETING_SOLD_COUNT, 0);
        if ($current <= 0) {
            Setting::setValue(Constants::SETTING_MARKETING_SOLD_COUNT, '1250');
        }
